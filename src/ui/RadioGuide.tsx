import { callTo, type RadioProfile } from '../config/stations';

/**
 * כרטיס נוהל קשר: מי זה מי, למי פונים על מה, ואיך מנסחים – לפי אותות הקריאה של התחנה שנבחרה.
 * עקרונות תרגול כלליים, לא מסמך נוהל רשמי.
 */
export function RadioGuide({ p }: { p: RadioProfile }) {
  const n = (x: string) => x;
  const me = p.unit;
  const ctr = p.real ? p.centerCall : 'מוקד אלון';
  const roles = p.real
    ? [
        [p.center, `„${p.centerCall}”`, 'פותח את האירוע ומנהל אותו מולך: מעביר פרטים, עונה לשאלות השלמה, מקבל קבלה, הגעה ועדכונים, שואל „אתה פנוי?”, מזמין מד״א, כב״ה, גורם מוסמך, גרר, איתור בעלים.'],
        [`ראש המשמרת – ${p.head}`, n(p.headNum), 'מחליט איזו ניידת מקבלת את האירוע ומבקש מהמשל״ט להעביר אליה („תעבירי ל־402”). תגבור – ניידת נוספת מבקשים ממנו; שואל „אתה פנוי?” ומקבל עדכון מצב; החלפת ניידת, הפסקות.'],
        [`קצין תורן – ${p.dutyOfficer}`, n(p.dutyNum), 'מעודכן באירוע משמעותי: נפגע, עיכוב, פינוי, חפץ חשוד, התנגדות.'],
        ['ניידות סיור', '402–405', 'מקבלות את האירוע מהמשל״ט ועובדות מולו: קבלה, הגעה, מצב, סיום.'],
        ['שיטור עירוני', '301–302', 'איכות חיים, רעש, חניה, סדר ציבורי ברשות.'],
      ]
    : [
        ['מוקד אלון (בדוי)', 'מוקד', 'פותח אירוע, מעביר פרטים, מקבל עדכונים ומזמין כוחות.'],
        ['קצין תורן', 'קצין תורן', 'מעודכן באירוע משמעותי.'],
      ];
  const examples: [string, string, string][] = [
    ['פתיחת אירוע', p.real ? `(${p.head} למשל״ט) „${p.centerCall} מ${p.head}, תעבירי את האירוע ל${p.unitNum}.”` : '—', `${me} מ${ctr}, …פרטי האירוע…`],
    ['שאלת השלמה', `${callTo(p, 'center')}, יש פרטים על המעורבים? נשק, נפגעים?`, `${me}, …מה שידוע…`],
    ['קבלת אירוע', `${callTo(p, 'center')}, קיבלתי את האירוע, יוצא.`, `${me}, קיבלתי.`],
    ['הגעה למקום', `${callTo(p, 'center')}, הגעתי למקום.`, `${me}, קיבלתי. עדכן כשיש תמונת מצב.`],
    ['תמונת מצב', `${callTo(p, 'center')}, נמצא ב… · מצב: … · אומת: … · חסר: … · נדרש: …`, `${me}, קיבלתי.`],
    ['הזמנת מד״א', `${callTo(p, 'center')}, תזמני לי מד״א לכתובת … – פצוע בהכרה, חתך במצח.`, `${me}, קיבלתי, מד״א בדרך.`],
    ['הזמנת כב״ה', `${callTo(p, 'center')}, נדרש כב״ה לכתובת … – ריח גז חזק, מפנה דיירים.`, `${me}, קיבלתי, כב״ה הוזנקו.`],
    ['תגבור – ניידת נוספת (מ־401)', `${callTo(p, 'head')}, מבקש ניידת נוספת למקום – שלושה מעורבים.`, `${me}, קיבלתי. שולח אליך ניידת נוספת.`],
    ['401 שואל „מה המצב? אתה פנוי?”', `${callTo(p, 'head')}, שלילי. עדכון: אני בזירה עם המעורבים, המצב בשליטה. ממשיך לתחקר ולברר, ואעדכן כשאתפנה.`, `${me}, קיבלתי. תמשיך, ותעדכן כשאתה פנוי.`],
    ['עדכון קצין תורן', `${callTo(p, 'duty')}, עדכון: חשוד מעוכב לבירור על בסיס עדות, נפגע מטופל.`, `${me}, קיבל.`],
    ['סיום', `${callTo(p, 'center')}, סיימתי באירוע. … (תוצאה). פנוי.`, `${me}, קיבלתי.`],
  ];
  return (
    <div className="radio-guide stack" data-testid="radio-guide">
      <p className="small muted">
        מבנה כל שידור: <b>למי – ממי – מה</b>, השולח באות קריאה מלא: „{ctr} מ{me}”. באירוע עובדים מול <b>{p.real ? p.center : 'המוקד'}</b> – ממנו מקבלים את הפרטים ואליו מדווחים. קצר, עובדתי, בלי קביעות. מי שקיבל – מאשר („{me}, קיבלתי”).
      </p>
      <h3>מי זה מי</h3>
      <table className="guide-table">
        <thead><tr><th>גורם</th><th>אות קריאה</th><th>תפקיד בקשר</th></tr></thead>
        <tbody>{roles.map((r) => <tr key={r[0]}><td>{r[0]}</td><td><bdi>{r[1]}</bdi></td><td>{r[2]}</td></tr>)}</tbody>
      </table>
      <h3>למי פונים על מה</h3>
      <ul>
        <li><b>{p.real ? p.center : 'המוקד'}</b> – כל ניהול האירוע: שאלות על הפרטים, קבלה, הגעה, תמונת מצב, פנוי/עסוק, סיום, מד״א, כב״ה, גורם מוסמך לחפץ חשוד, גרר/פקח, איתור בעלים, הפצת תיאור.</li>
        {p.real && <li><b>{p.headNum}</b> – תגבור ניידת, החלפת ניידת, ענייני משמרת. בתחילת האירוע הוא מבקש מהמשל״ט להעביר אליך את האירוע.</li>}
        <li><b>{p.real ? `קצין תורן ${p.dutyNum}` : 'קצין תורן'}</b> – נפגע, עיכוב, פינוי, חפץ חשוד, סירוב או התנגדות.</li>
      </ul>
      <h3>דוגמאות שידור</h3>
      <table className="guide-table">
        <thead><tr><th>מצב</th><th>אתה משדר</th><th>תשובה</th></tr></thead>
        <tbody>{examples.map((e) => <tr key={e[0]}><td>{e[0]}</td><td>„{e[1]}”</td><td>„{e[2]}”</td></tr>)}</tbody>
      </table>
      <p className="small muted">עקרונות לתרגול בלבד. ניסוחים ואותות קריאה בתחנות שסומנו „משוער” – לפי ההיגיון של תחנות כפר סבא ונתניה; המדריך יכול לעדכן.</p>
    </div>
  );
}

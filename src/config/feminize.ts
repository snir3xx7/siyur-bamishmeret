/** משוב, רמזים והסברים לשוטרת: ציווי ופנייה בלשון נקבה */
export function feminizeFeedback(text: string): string {
  let t = text.replace(IMP_RE, (_, pre: string, w: string) => `${pre}${IMP[w] ?? w}`);
  t = t.replace(NEG_RE, (_, pre: string, w: string) => `${pre}אל ${w}י`);
  for (const [a, b] of YOU) t = t.split(a).join(b);
  return t;
}

/** מפעיל את feminizeFeedback על כל המחרוזות במבנה (תחקיר, כרטיסים) */
export function femDeep<T>(v: T): T {
  if (typeof v === 'string') return feminizeFeedback(v) as T;
  if (Array.isArray(v)) return v.map(femDeep) as T;
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, ['rule', 'id', 'lines', 'ref'].includes(k) ? x : femDeep(x)])) as T;
  return v;
}
